// Turns the nemesis screen's sample pages (TPTests "[.nemeses.dump]", run with NEMESIS_DUMP set to a folder) into the
// overlay mock's data: Code/skyrim_ui/src/app/mock/nemesis-samples.ts. The pages are the server's own JSON, so the
// mock shows what the game will.
// usage: node Tools/NemesisMockSamples.js <dump folder>
const fs = require('fs');
const path = require('path');

const folder = process.argv[2];
if (!folder)
  throw new Error('usage: node Tools/NemesisMockSamples.js <dump folder>');
const out = path.join(__dirname, '..', 'Code', 'skyrim_ui', 'src', 'app', 'mock', 'nemesis-samples.ts');

const pages = {};
for (const file of fs.readdirSync(folder).filter(name => name.endsWith('.json')).sort())
  pages[file.slice(0, -5)] = JSON.parse(fs.readFileSync(path.join(folder, file), 'utf8'));

const text = `// Generated by Tools/NemesisMockSamples.js from the server's own pages (TPTests "[.nemeses.dump]"): do not edit.
// Keys: record, world, wounds, gang_<id>, man_<id>, gunpoint, card.
/* eslint-disable */
export const nemesisSamples: Record<string, any> = ${JSON.stringify(pages, null, 1)};
`;
fs.writeFileSync(out, text);
console.log(`${out}: ${Object.keys(pages).length} pages, ${text.length} characters`);
