# Writes ParkourMoves.h from the exported clips' JSON (finalize.py): per move and view, the animation file, its
# length, the travel curve (one point per 30 fps frame), the sound cues, and in first person the view's motion.
# Usage: make_header.py <out folder with 3p/ and 1p/> <ParkourMoves.h>
import json, os, sys

MOVES = ['Fail', 'Grab', 'GrabHigh', 'Vault', 'StepLowLeft', 'StepLowRight', 'StepHighLeft', 'StepHighRight',
         'ClimbLow', 'ClimbMedium', 'ClimbHigh', 'ClimbHighest', 'LandRoll']
# the clips' sound annotations -> our cues (Rustling, Cloth and Whip have no sound of ours yet)
SOUNDS = {'SoundPlay.SPPF_Jump': 'kJump', 'SoundPlay.SPPF_JumpLand': 'kLand', 'SoundPlay.SPPF_Touch': 'kTouch'}
FILES = {'3p': 'Actors\\\\Character\\\\Animations\\\\ReclamationDay\\\\Parkour\\\\{}.hkx',
         '1p': 'Actors\\\\Character\\\\_1stPerson\\\\Animations\\\\ReclamationDay\\\\Parkour\\\\{}.hkx'}

out_dir, header = sys.argv[1:3]
lines = ['#pragma once', '',
         '// Generated by Tools/ConvertParkourAnimations/make_header.py from the exported clips - do not edit by hand.',
         '// The parkour moves: the animation each view plays (as a dynamic idle) and how far the character travels with it',
         '// (x right, y forward, z up in its own frame, game units, one point per 1/30 s from the clip\'s start).',
         '', '#include <cstdint>', '', 'namespace ParkourMoves', '{',
         'enum class Move : uint8_t', '{']
lines += [f'    k{m},' for m in MOVES] + ['    kCount,', '};', '',
          'enum class Sound : uint8_t', '{', '    kJump,', '    kTouch,', '    kLand,', '};', '',
          'struct Cue', '{', '    float Time;', '    Sound Kind;', '};', '',
          'struct View', '{', '    const char* File;', '    // seconds', '    float Duration;',
          '    // the travel is settled from here (seconds)', '    float Settled;',
          '    uint16_t FrameCount;', '    const float (*Curve)[3];', '    const Cue* Cues;', '    uint8_t CueCount;',
          '    // first person, per frame: the view against where it rests (x right, y forward, z up, game units) and how',
          "    // it's turned (pitch down, yaw right, radians); none in third person", '    const float (*Eye)[5];', '};', '',
          'inline constexpr float kFrameTime = 1.f / 30.f;', '']
views = {}
for m in MOVES:
    for v in ('3p', '1p'):
        i = json.load(open(os.path.join(out_dir, v, m + '.json')))
        ident = f'k{m}{v.upper()}'
        lines.append(f'inline constexpr float {ident}Curve[][3] = {{')
        for c in i['curve']:
            lines.append('    {' + ', '.join(f'{x:.3f}f' for x in c) + '},')
        lines.append('};')
        cues = [(t, SOUNDS[e]) for t, e in i['events'] if e in SOUNDS]
        lines.append(f'inline constexpr Cue {ident}Cues[] = {{' + ', '.join(f'{{{t:.4f}f, Sound::{k}}}' for t, k in cues) +
                     ('' if cues else '{-1.f, Sound::kJump}') + '};')
        if 'eye' in i:
            lines.append(f'inline constexpr float {ident}Eye[][5] = {{')
            for e in i['eye']:
                lines.append('    {' + ', '.join(f'{x:.4f}f' for x in e) + '},')
            lines.append('};')
        views[(m, v)] = (FILES[v].format(m), i['duration'], i['settled'], len(i['curve']), ident, len(cues), 'eye' in i)
lines += ['', '// [move][0] third person, [move][1] first person', 'inline constexpr View kViews[][2] = {']
for m in MOVES:
    row = []
    for v in ('3p', '1p'):
        f, d, s, n, ident, nc, eye = views[(m, v)]
        row.append(f'{{"{f}", {d:.4f}f, {s:.4f}f, {n}, {ident}Curve, {ident}Cues, {nc}, ' + (f'{ident}Eye' if eye else 'nullptr') + '}')
    lines.append('    {' + ', '.join(row) + '},')
lines += ['};', '', 'inline constexpr const char* kNames[] = {' + ', '.join(f'"{m}"' for m in MOVES) + '};', '',
          'static_assert(sizeof(kViews) / sizeof(kViews[0]) == static_cast<size_t>(Move::kCount));',
          '} // namespace ParkourMoves', '']
open(header, 'w', newline='\n').write('\n'.join(lines))
print(header, sum(views[k][3] for k in views), 'curve points,', len(MOVES), 'moves')
