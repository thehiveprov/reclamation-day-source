// Writes the first person weapon subgraphs of HumanRaceSubGraphData (Fallout4.esm 0x166729) as a C++ table: each entry's
// target keywords (the weapon's: all must be there; the entry with the most wins) and its animation folders in the
// order the game looks in them. usage: node subtable.js <Fallout4.esm> <out.inl>
const L = require('F:/modfiles/RDWinterOfAtom/tools/esp/esplib.js');
const fs = require('fs');
const [file, out] = process.argv.slice(2);
const p = L.readPlugin(file);
const rec = p.byId.get(0x166729);
const edid = id => { const r = p.byId.get(id); return r ? (L.edidOf(r) || id.toString(16)) : id.toString(16); };
let cur = null; const entries = [];
for (const [t, d] of L.subsOf(rec)) {
  if ((t === 'SAKD' || t === 'STKD') && (!cur || cur.done)) { cur = { actor: [], target: [], paths: [] }; entries.push(cur); }
  if (!cur) continue;
  if (t === 'SAKD') for (let i = 0; i + 4 <= d.length; i += 4) cur.actor.push(d.readUInt32LE(i));
  else if (t === 'STKD') for (let i = 0; i + 4 <= d.length; i += 4) cur.target.push(d.readUInt32LE(i));
  else if (t === 'SAPT') cur.paths.push(d.toString('latin1').replace(/\0.*$/s, ''));
  else if (t === 'SRAF') cur.done = true;
}
const lines = [];
let kept = 0;
for (const e of entries) {
  const firstPerson = /_1stperson.animations./i;
  if (e.actor.length || !e.target.length || !e.paths.some(x => firstPerson.test(x))) continue;
  const folders = e.paths.filter(x => firstPerson.test(x)).map(x => x.replace(/^.*_1stperson.animations./i, '')).filter(x => !/^(paired|common)$/i.test(x));
  if (!folders.length || e.target.length > 4 || folders.length > 4) continue;
  const keys = e.target.map(k => `0x${k.toString(16).toUpperCase()}`).join(', ');
  lines.push(`    {{${keys}}, ${e.target.length}, {${folders.map(f => JSON.stringify(f)).join(', ')}}}, // ${e.target.map(edid).join(', ')}`);
  ++kept;
}
fs.writeFileSync(out, `// Generated by Tools/DualWieldGrips/subtable.js from Fallout4.esm's HumanRaceSubGraphData (0x166729): the first person\n// weapon subgraphs, their target keywords and the folders under Meshes/Actors/Character/_1stPerson/Animations they\n// take clips from, in order (Paired and Common left out). ${kept} entries.\n` + lines.join('\n') + '\n');
console.log(kept, 'entries written');
