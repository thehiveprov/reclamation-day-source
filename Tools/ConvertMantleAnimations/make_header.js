// Writes the retargeted climbs (mantle_grabs.json from retarget.py) as a C++ header for the client
// usage: node make_header.js <mantle_grabs.json> <out.h>
const fs = require('fs');
const [input, output] = process.argv.slice(2);
const data = JSON.parse(fs.readFileSync(input, 'utf8'));

// Rotation rows (as the game's NiMatrix3 stores them) -> quaternion w, x, y, z
function toQuaternion(m) {
  const [[a, b, c], [d, e, f], [g, h, i]] = m;
  const trace = a + e + i;
  let w, x, y, z;
  if (trace > 0) { const s = Math.sqrt(trace + 1) * 2; w = s / 4; x = (h - f) / s; y = (c - g) / s; z = (d - b) / s; }
  else if (a > e && a > i) { const s = Math.sqrt(1 + a - e - i) * 2; w = (h - f) / s; x = s / 4; y = (b + d) / s; z = (c + g) / s; }
  else if (e > i) { const s = Math.sqrt(1 + e - a - i) * 2; w = (c - g) / s; x = (b + d) / s; y = s / 4; z = (f + h) / s; }
  else { const s = Math.sqrt(1 + i - a - e) * 2; w = (d - b) / s; x = (c + g) / s; y = (f + h) / s; z = s / 4; }
  const n = Math.hypot(w, x, y, z);
  return [w / n, x / n, y / n, z / n];
}
const f = (v) => (Math.abs(v) < 5e-7 ? '0.f' : `${v.toFixed(6)}f`);

let out = `#pragma once

// GENERATED by Tools/ConvertMantleAnimations (retarget.py in Blender with PyNifly, then make_header.js): don't edit,
// re-run the converter.
//
// The first-person climb animations of Mantle for Fallout: New Vegas by STRADAT (Nexus New Vegas mod 99083, used
// with permission), retargeted onto Fallout 4's first-person skeleton (Actors\\Character\\_1stPerson\\CharacterAssets): the
// hand(s) reaching for the ledge and pulling over. Only the arms the climb moves are listed; everything else stays as
// the game animates it.
//
// Each key is a bone's LOCAL transform (relative to its parent, as NiAVObject::local at 0x30 holds it): a rotation
// quaternion (w, x, y, z; see ToRows for the game's row layout) and, for the collarbones only, a translation (the New
// Vegas animation lifts the collarbone to bring the arm into view). Frames are at ${data.fps} fps, frame-major:
// keys[frame * boneCount + bone].
namespace MantleGrabAnimations
{
constexpr float kFps = ${data.fps}.f;

struct Key
{
    float rotation[4]; // w, x, y, z
    float translation[3];
    bool hasTranslation;
};

struct Clip
{
    const char* name;
    int frameCount;
    int boneCount;
    const char* const* bones; // first-person skeleton node names
    const Key* keys;
};

// A quaternion as the 3x3 rotation rows NiMatrix3 stores (row r, column c)
inline void ToRows(const float acQ[4], float aRows[3][3]) noexcept
{
    const float w = acQ[0], x = acQ[1], y = acQ[2], z = acQ[3];
    aRows[0][0] = 1 - 2 * (y * y + z * z); aRows[0][1] = 2 * (x * y - w * z);     aRows[0][2] = 2 * (x * z + w * y);
    aRows[1][0] = 2 * (x * y + w * z);     aRows[1][1] = 1 - 2 * (x * x + z * z); aRows[1][2] = 2 * (y * z - w * x);
    aRows[2][0] = 2 * (x * z - w * y);     aRows[2][1] = 2 * (y * z + w * x);     aRows[2][2] = 1 - 2 * (x * x + y * y);
}
`;

const clipNames = [];
for (const [name, clip] of Object.entries(data.clips)) {
  const bones = Object.keys(clip.frames[0]).sort();
  const id = name.charAt(0).toUpperCase() + name.slice(1);
  clipNames.push([name, id, clip.frames.length, bones.length]);
  out += `\n// ${name}: ${clip.frames.length} frames, ${clip.sides.map((s) => (s === 'L' ? 'left' : 'right')).join(' and ')} arm\n`;
  out += `inline constexpr const char* k${id}Bones[] = {${bones.map((b) => `"${b}"`).join(', ')}};\n`;
  out += `inline constexpr Key k${id}Keys[] = {\n`;
  for (const frame of clip.frames) {
    for (const bone of bones) {
      const e = frame[bone];
      const q = toQuaternion(e.rotation);
      const t = e.translation || [0, 0, 0];
      out += `    {{${q.map(f).join(', ')}}, {${t.map(f).join(', ')}}, ${e.translation ? 'true' : 'false'}},\n`;
    }
  }
  out += `};\n`;
}
out += `\ninline constexpr Clip kClips[] = {\n${clipNames.map(([n, id, fc, bc]) => `    {"${n}", ${fc}, ${bc}, k${id}Bones, k${id}Keys},`).join('\n')}\n};\n} // namespace MantleGrabAnimations\n`;
fs.writeFileSync(output, out);
