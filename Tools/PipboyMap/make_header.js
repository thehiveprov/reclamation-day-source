// retarget_glance.py's JSON -> Code/client/Games/Fallout4/PipboyGlanceAnimation.h
// usage: node make_header.js <glance.json> <out.h>
const fs = require('fs');
const [input, output] = process.argv.slice(2);
const clip = JSON.parse(fs.readFileSync(input, 'utf8'));

// a rotation's quaternion (w, x, y, z) from its rows (rows[r][c], column vectors: the columns are the bone's axes)
function quaternion(m) {
  const trace = m[0][0] + m[1][1] + m[2][2];
  let q;
  if (trace > 0) {
    const s = Math.sqrt(trace + 1) * 2;
    q = [0.25 * s, (m[2][1] - m[1][2]) / s, (m[0][2] - m[2][0]) / s, (m[1][0] - m[0][1]) / s];
  } else if (m[0][0] > m[1][1] && m[0][0] > m[2][2]) {
    const s = Math.sqrt(1 + m[0][0] - m[1][1] - m[2][2]) * 2;
    q = [(m[2][1] - m[1][2]) / s, 0.25 * s, (m[0][1] + m[1][0]) / s, (m[0][2] + m[2][0]) / s];
  } else if (m[1][1] > m[2][2]) {
    const s = Math.sqrt(1 + m[1][1] - m[0][0] - m[2][2]) * 2;
    q = [(m[0][2] - m[2][0]) / s, (m[0][1] + m[1][0]) / s, 0.25 * s, (m[1][2] + m[2][1]) / s];
  } else {
    const s = Math.sqrt(1 + m[2][2] - m[0][0] - m[1][1]) * 2;
    q = [(m[1][0] - m[0][1]) / s, (m[0][2] + m[2][0]) / s, (m[1][2] + m[2][1]) / s, 0.25 * s];
  }
  const l = Math.hypot(...q);
  return q.map((v) => v / l);
}

const bones = Object.keys(clip.frames[0]);
// keep each bone's quaternions on one side, so slerping between frames takes the short way
const last = {};
const keys = clip.frames.map((frame) =>
  bones.map((name) => {
    const { rotation, translation } = frame[name].camera;
    let q = quaternion(rotation);
    if (last[name] && q.reduce((a, v, i) => a + v * last[name][i], 0) < 0) q = q.map((v) => -v);
    last[name] = q;
    return `    {{${q.map((v) => v.toFixed(6) + 'f').join(', ')}}, {${translation.map((v) => v.toFixed(4) + 'f').join(', ')}}},`;
  }).join('\n')
);
const markers = clip.markers.map(([t, text]) => `    {${t.toFixed(4)}f, "${text}"},`).join('\n');

const header = `#pragma once

// Generated by Tools/PipboyMap/make_header.js from Realtime Pip-Boy Map's Check.kf (Fallout: New Vegas, by Stentorious,
// xConfused and Hitman; used with permission), retargeted by Tools/PipboyMap/retarget_glance.py onto Fallout 4's
// first-person arms (the left raises the Pip-Boy, the right hangs down out of view). Don't edit by hand.
//
// Per frame and bone: the bone's transform relative to the first-person skeleton's Camera bone, in the Fallout 4 model
// space convention (column vectors: world = camera * key); rotations as quaternions (w, x, y, z). The game stores a
// node's rotation transposed (docs/ANIMATION_PIPELINE.md, 6.3).
namespace PipboyGlanceAnimation
{
struct Key
{
    float rotation[4];
    float translation[3];
};

struct Marker
{
    float time;
    const char* text;
};

inline constexpr float kFps = ${clip.fps}.f;
inline constexpr int kFrameCount = ${clip.frames.length};
inline constexpr int kBoneCount = ${bones.length};
inline constexpr const char* kCameraBone = "Camera";

// parents before their children
inline constexpr const char* kBones[kBoneCount] = {
${bones.map((b) => `    "${b}",`).join('\n')}
};

inline constexpr Marker kMarkers[] = {
${markers}
};

// kFrameCount x kBoneCount, frame by frame
inline constexpr Key kKeys[kFrameCount * kBoneCount] = {
${keys.join('\n')}
};
} // namespace PipboyGlanceAnimation
`;
fs.writeFileSync(output, header.replace(/\r\n/g, '\n'));
console.log(`wrote ${output} ${clip.frames.length} frames x ${bones.length} bones`);
